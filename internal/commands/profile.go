package commands

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/cedaniel200/atlasctl/internal/fsutil"
	"github.com/cedaniel200/atlasctl/internal/setup"
	"github.com/cedaniel200/atlasctl/internal/state"
)

// ErrProfileExists reports an existing profile that would need --force.
var ErrProfileExists = errors.New("commands: profile already exists; use --force")

// ProfileDetection is a proposal read from the repository.
type ProfileDetection struct {
	Proposal setup.ProfileProposal
	Found    bool
	Path     string
}

// ProfileWriteRequest writes a proposed profile as project data.
type ProfileWriteRequest struct {
	Project  string
	Proposal setup.ProfileProposal
	Force    bool
}

// ProfileWriteResult is the path written and the profile recorded in state.
type ProfileWriteResult struct {
	Path    string
	Profile string
}

// DetectProfile proposes a profile and its destination path.
func DetectProfile(project string) ProfileDetection {
	proposal, ok := setup.DetectProfile(project)
	detection := ProfileDetection{Proposal: proposal, Found: ok}
	if ok {
		if path, err := ProfilePath(proposal.ID); err == nil {
			detection.Path = path
		}
	}
	return detection
}

// ProfilePath returns the project-relative path of a profile.
func ProfilePath(id string) (string, error) {
	if id == "" || id == "." || id == ".." || strings.ContainsAny(id, `/\`) {
		return "", fmt.Errorf("commands: invalid profile id %q", id)
	}
	path := ".atlas/profiles/" + id + ".yaml"
	if err := fsutil.ValidateRelative(path); err != nil {
		return "", fmt.Errorf("commands: invalid profile id %q: %w", id, err)
	}
	return path, nil
}

// ProfileExists reports whether the profile file already exists.
func ProfileExists(project, id string) bool {
	path, err := ProfilePath(id)
	if err != nil {
		return false
	}
	_, err = os.Stat(filepath.Join(project, filepath.FromSlash(path)))
	return err == nil
}

// WriteProfile writes the YAML as project data and updates state.Profile. It
// refuses an existing file unless Force is set.
func WriteProfile(request ProfileWriteRequest) (ProfileWriteResult, error) {
	if request.Project == "" {
		return ProfileWriteResult{}, errors.New("commands: project root is required")
	}
	path, err := ProfilePath(request.Proposal.ID)
	if err != nil {
		return ProfileWriteResult{}, err
	}
	if err := fsutil.CheckNoSymlinks(request.Project, path); err != nil {
		return ProfileWriteResult{}, err
	}
	absolute, err := fsutil.SafeJoin(request.Project, path)
	if err != nil {
		return ProfileWriteResult{}, err
	}

	statePath := filepath.Join(request.Project, ".atlas", "state.json")
	current, err := loadState(statePath)
	if err != nil {
		return ProfileWriteResult{}, err
	}
	if current == nil {
		return ProfileWriteResult{}, ErrNotConfigured
	}

	var original []byte
	var originalMode os.FileMode
	existing := false
	if info, statErr := os.Lstat(absolute); statErr == nil {
		if !info.Mode().IsRegular() {
			return ProfileWriteResult{}, fmt.Errorf("commands: profile %q is not a regular file", path)
		}
		existing = true
		originalMode = info.Mode().Perm()
		original, err = os.ReadFile(absolute)
		if err != nil {
			return ProfileWriteResult{}, err
		}
	} else if !errors.Is(statErr, os.ErrNotExist) {
		return ProfileWriteResult{}, statErr
	}
	if existing && !request.Force {
		return ProfileWriteResult{}, fmt.Errorf("%w: %s", ErrProfileExists, path)
	}

	data := renderProfile(request.Proposal)
	if err := fsutil.WriteProjectFile(request.Project, path, data); err != nil {
		return ProfileWriteResult{}, err
	}
	current.Profile = request.Proposal.ID
	if err := state.Save(statePath, current); err != nil {
		if existing {
			_ = os.WriteFile(absolute, original, originalMode)
		} else {
			_ = fsutil.RemoveProjectFile(request.Project, path)
		}
		return ProfileWriteResult{}, err
	}
	return ProfileWriteResult{Path: path, Profile: request.Proposal.ID}, nil
}

func renderProfile(proposal setup.ProfileProposal) []byte {
	var builder strings.Builder
	builder.WriteString("# Generated by atlasctl profile detect. A profile is DATA: commands and paths.\n")
	builder.WriteString("# Unknown values are TBD; validate them by running them before relying on the profile.\n")
	fmt.Fprintf(&builder, "name: %s\n", proposal.ID)
	fmt.Fprintf(&builder, "description: %s\n\n", yamlValue(proposal.Description))
	builder.WriteString("stack:\n")
	fmt.Fprintf(&builder, "  language: %s\n", yamlValue(proposal.Language))
	fmt.Fprintf(&builder, "  runtime: %s\n", yamlValue(proposal.Runtime))
	fmt.Fprintf(&builder, "  package_manager: %s\n\n", yamlValue(proposal.PackageManager))
	builder.WriteString("structure:\n")
	fmt.Fprintf(&builder, "  source: %s\n", yamlValue(proposal.Source))
	fmt.Fprintf(&builder, "  tests: %s\n\n", yamlValue(proposal.Tests))
	builder.WriteString("commands:\n")
	for _, command := range []string{
		"install", "build", "run", "test", "test_unit", "lint", "lint_tests",
		"typecheck", "static_analysis", "quality", "coverage", "mutation", "crap",
	} {
		fmt.Fprintf(&builder, "  %s: \"TBD\"\n", command)
	}
	builder.WriteString("\nnotes: |\n")
	fmt.Fprintf(&builder, "  Proposed from %s.\n", strings.Join(proposal.Evidence, ", "))
	builder.WriteString("  TBD means unknown: validate each value by running it before relying on the profile.\n")
	builder.WriteString("  N/A means the concept does not apply.\n")
	return []byte(builder.String())
}

func yamlValue(value string) string {
	value = strings.ReplaceAll(value, `\`, `\\`)
	value = strings.ReplaceAll(value, `"`, `\"`)
	return `"` + value + `"`
}
